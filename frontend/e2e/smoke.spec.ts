  await expect(page.getByRole('group', { name: '供應據點經緯度圖' })).toBeVisible()
  await page.getByRole('button', { name: '風險事件' }).click()
  await expect(page.getByRole('heading', { name: '風險事件' })).toBeVisible()
  await expect(page.getByRole('heading', { name: '登錄事件' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'What-if 分析' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: '情報審查' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'L2 替代採購提案' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'L3 人工核准' })).toHaveCount(0)
  await page.getByRole('button', { name: '決策紀錄' }).click()
  await page.locator('.rows > li').filter({ hasText: 'E2E 港口延誤時哪些採購單受影響？' }).getByRole('button', { name: '查看證據' }).click()
