test('planner submits and a different approver completes one ERP effect', async ({ page }) => {
  await login(page, 'planner', 'planner')
  await page.getByRole('button', { name: 'L2 替代採購提案' }).click()
  const order = page.locator('.rows > li').filter({ hasText: 'E2E-DELAYED' })
  await expect(order).toBeVisible()
  await order.getByRole('button', { name: '查看備援來源' }).click()
  await expect(page.getByLabel('備援供應商')).toBeVisible()
  await page.getByRole('button', { name: '送交 L3 核准' }).click()
  await expect(page.getByRole('status')).toContainText('已送交 L3 審核')

  await page.getByRole('button', { name: '登出' }).click()
  await login(page, 'approver', 'approver')
  await page.getByRole('button', { name: 'L3 人工核准' }).click()
  const approval = page.locator('.rows > li').filter({ hasText: 'proposal:create-po:' })
  await expect(approval).toBeVisible()
  await approval.getByRole('button', { name: '審查' }).click()
  await expect(page.getByRole('heading', { name: '提案證據' })).toBeVisible()
  await page.getByRole('button', { name: '核准並執行' }).click()
  await expect(page.getByText('執行完成')).toBeVisible()
  await expect(page.getByText('收據：', { exact: false })).toBeVisible()
  await expect(page.getByText('目前沒有待審核的替代採購提案。')).toBeVisible()
})

